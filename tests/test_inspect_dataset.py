DATA_YAML = (
    "train: ../train/images\n"
    "val: ../valid/images\n"
    "test: ../test/images\n"
    "\n"
    "nc: {nc}\n"
    "names: {names}\n"
)

ROBOFLOW_README = (
    "Dataset exported from Roboflow Universe.\n"
    "License: CC BY 4.0\n"
    "https://universe.roboflow.com/example-ws/example-project/dataset/1\n"
)


def _png_bytes(width: int, height: int, seed: int = 0) -> bytes:
    """Return deterministic PNG bytes for a small synthetic image."""
    import cv2

    rng = np.random.default_rng(seed)
    img = rng.integers(0, 256, (height, width, 3), dtype=np.uint8)
    ok, buf = cv2.imencode(".png", img)
    assert ok
    return buf.tobytes()


def _jpg_bytes(width: int, height: int, seed: int = 0) -> bytes:
    import cv2

    rng = np.random.default_rng(seed)
    img = rng.integers(0, 256, (height, width, 3), dtype=np.uint8)
    ok, buf = cv2.imencode(".jpg", img)
    assert ok
    return buf.tobytes()


def build_zip(
    path: Path,
    splits: dict[str, list[tuple[str, str, bytes]]],
    *,
    names: tuple[str, ...] = ("goggles", "no_goggles"),
    nc: int | None = None,
    data_yaml: str | None = None,
    extra_members: dict[str, bytes] | None = None,
) -> Path:
    """Write a synthetic Roboflow-shaped ZIP.

    ``splits`` maps a split name to a list of ``(image_filename, label_text,
    image_bytes)`` tuples. ``label_text`` of ``None`` omits the label file.
    """
    if nc is None:
        nc = len(names)
    if data_yaml is None:
        data_yaml = DATA_YAML.format(nc=nc, names=list(names))

    with zipfile.ZipFile(path, "w") as zf:
        zf.writestr("data.yaml", data_yaml)
        zf.writestr("README.roboflow.txt", ROBOFLOW_README)
        for split, entries in splits.items():
            for filename, label_text, image_bytes in entries:
                zf.writestr(f"{split}/images/{filename}", image_bytes)
                if label_text is not None:
                    stem = Path(filename).stem
                    zf.writestr(f"{split}/labels/{stem}.txt", label_text)
        for name, blob in (extra_members or {}).items():
            zf.writestr(name, blob)
    return path


def one_class_box(cls: int = 0) -> str:
    return f"{cls} 0.5 0.5 0.2 0.2\n"


def run_summary(archive: Path, out: Path, art: Path | None = None) -> dict:
    """Run the auditor and return only its structured summary mapping."""
    result = insp.run_audit(
        zip_path=archive,
        out_dir=out,
        artifacts_dir=art,
        make_contact_sheets=False,
    )
    return result["summary"]



# --------------------------------------------------------------------------
# 1. Read-only guarantee
# --------------------------------------------------------------------------


def test_audit_does_not_modify_source_zip(tmp_path: Path) -> None:
    """The source archive is byte-identical and keeps its mtime after an audit."""
    archive = build_zip(
        tmp_path / "src.zip",
        {"train": [("a.jpg", one_class_box(), _jpg_bytes(64, 48, 1))]},
    )
    before_bytes = archive.read_bytes()
    before_stat = archive.stat()

    insp.main(
        [
            "--zip", str(archive),
            "--out", str(tmp_path / "out"),
            "--artifacts", str(tmp_path / "art"),
            "--no-contact-sheets",
        ]
    )

    assert archive.read_bytes() == before_bytes
    after_stat = archive.stat()
    assert after_stat.st_size == before_stat.st_size
    assert after_stat.st_mtime == before_stat.st_mtime


def test_audit_writes_only_inside_out_dir(tmp_path: Path) -> None:
    """No file appears next to the archive; all records land in --out."""
    src_dir = tmp_path / "raw"
    src_dir.mkdir()
    archive = build_zip(
        src_dir / "src.zip",
        {"train": [("a.jpg", one_class_box(), _jpg_bytes(64, 48, 2))]},
    )
    out = tmp_path / "out"

    insp.main(
        [
            "--zip", str(archive),
            "--out", str(out),
            "--artifacts", str(tmp_path / "art"),
            "--no-contact-sheets",
        ]
    )

    assert sorted(p.name for p in src_dir.iterdir()) == ["src.zip"]
    assert (out / "dataset_summary.json").is_file()



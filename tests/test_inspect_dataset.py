def test_missing_zip_raises_readable_error(tmp_path: Path) -> None:
    with pytest.raises(insp.AuditInputError) as excinfo:
        insp.run_audit(
            zip_path=tmp_path / "nope.zip",
            out_dir=tmp_path / "out",
            artifacts_dir=tmp_path / "art",
            make_contact_sheets=False,
        )
    assert "nope.zip" in str(excinfo.value)


def test_non_zip_file_raises_readable_error(tmp_path: Path) -> None:
    bad = tmp_path / "not_a.zip"
    bad.write_bytes(b"this is definitely not a zip archive")

    with pytest.raises(insp.AuditInputError) as excinfo:
        insp.run_audit(
            zip_path=bad,
            out_dir=tmp_path / "out",
            artifacts_dir=tmp_path / "art",
            make_contact_sheets=False,
        )
    assert "ZIP" in str(excinfo.value) or "zip" in str(excinfo.value)


def test_main_returns_exit_2_on_bad_input(tmp_path: Path, capsys) -> None:
    """A bad path exits 2 with an ERROR: line and no traceback."""
    code = insp.main(["--zip", str(tmp_path / "missing.zip"), "--out", str(tmp_path / "out")])
    captured = capsys.readouterr()
    assert code == 2
    assert "ERROR:" in captured.err
    assert "Traceback" not in captured.err


def test_missing_data_yaml_is_fatal(tmp_path: Path) -> None:
    archive = tmp_path / "nodata.zip"
    with zipfile.ZipFile(archive, "w") as zf:
        zf.writestr("train/images/a.jpg", _jpg_bytes(64, 48, 3))

    with pytest.raises(insp.AuditInputError) as excinfo:
        run_summary(archive, tmp_path / "out")
    assert "data.yaml" in str(excinfo.value)


def test_nc_mismatch_with_names_is_fatal(tmp_path: Path) -> None:
    """nc must equal len(names); a mismatch is a fatal metadata error."""
    archive = build_zip(
        tmp_path / "mismatch.zip",
        {"train": [("a.jpg", one_class_box(), _jpg_bytes(64, 48, 4))]},
        names=("goggles", "no_goggles"),
        nc=5,
    )
    with pytest.raises(insp.AuditInputError) as excinfo:
        run_summary(archive, tmp_path / "out")
    assert "nc" in str(excinfo.value)



"""Tests for the Phase 1 dataset auditor (``tools/inspect_dataset.py``).

Every fixture here is synthesised in ``tmp_path`` at test time. No test opens,
reads, extracts, or otherwise touches the real source archive, and no test
depends on the real dataset being present. That keeps the suite fast, fully
offline, and free of any licensing or distribution question: the synthetic
images are generated by this file, not copied from the Roboflow export.

The suite is organised around the guarantees the auditor makes:

* it is read-only and never mutates the source archive;
* it fails with a readable message (never a traceback) on invalid input;
* it detects structural problems (malformed rows, missing pairs, leakage);
* its structured output is deterministic for a fixed seed.
"""

from __future__ import annotations

import json
import sys
import zipfile
from pathlib import Path

import numpy as np
import pytest

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from tools import inspect_dataset as insp  # noqa: E402



def test_two_runs_produce_identical_records(tmp_path: Path) -> None:
    """Re-running with the same seed reproduces every record exactly."""
    archive = build_zip(
        tmp_path / "det.zip",
        {
            "train": [
                (f"img{i}.jpg", one_class_box(), _jpg_bytes(64, 48, 100 + i))
                for i in range(5)
            ]
        },
    )
    out_a, out_b = tmp_path / "a", tmp_path / "b"
    run_summary(archive, out_a)
    run_summary(archive, out_b)

    def masked(path: Path) -> str:
        payload = json.loads(path.read_text())
        for key in ("generated_at_utc", "started_at_utc", "finished_at_utc"):
            payload.pop(key, None)
        # The output directory is an input, not a result: two runs into two
        # different directories must still agree on every recorded finding.
        payload.get("arguments", {}).pop("out_dir", None)
        return json.dumps(payload, sort_keys=True)

    for name in ("dataset_summary.json", "audit_run_metadata.json"):
        assert masked(out_a / name) == masked(out_b / name)
    for name in ("source_manifest.csv", "class_counts.csv", "split_leakage.csv"):
        assert (out_a / name).read_bytes() == (out_b / name).read_bytes()


def test_all_thirteen_outputs_are_written(tmp_path: Path) -> None:
    archive = build_zip(
        tmp_path / "outs.zip",
        {"train": [("a.jpg", one_class_box(), _jpg_bytes(64, 48, 19))]},
    )
    run_summary(archive, tmp_path / "out")
    expected = {
        "source_manifest.csv",
        "class_counts.csv",
        "image_statistics.csv",
        "annotation_statistics.csv",
        "annotation_issues.csv",
        "missing_pairs.csv",
        "corrupt_images.csv",
        "exact_duplicates.csv",
        "near_duplicates.csv",
        "split_leakage.csv",
        "manual_review_queue.csv",
        "dataset_summary.json",
        "audit_run_metadata.json",
    }
    written = {p.name for p in (tmp_path / "out").iterdir() if p.is_file()}
    assert expected <= written


